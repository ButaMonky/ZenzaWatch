'use strict';
// Guard against silently losing strict SCUI sources while migrating the
// remaining legacy scene modules. This is coverage, not a completeness claim.
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'../..');
const scene=path.join(root,'packages/zenza/src/sceneSearch');
const typed=path.join(root,'tools/typescript-stage1/nico-src');
const manifest=JSON.parse(fs.readFileSync(
 path.join(root,'tools/typescript-stage1/scui-runtime-manifest.json'),'utf8'));

function jsFiles(dir){
 return fs.readdirSync(dir,{withFileTypes:true}).flatMap(entry=>{
  const p=path.join(dir,entry.name);
  if(entry.isDirectory())return jsFiles(p);
  return entry.isFile()&&p.endsWith('.js')?[p]:[];
 });
}
const files=jsFiles(scene);
const names=files.map(p=>path.basename(p,'.js'));
const migrated=names.filter(name=>fs.existsSync(path.join(typed,name+'.ts')));

describe('SCUI TypeScript migration does not regress',()=>{
 it('accounts for every legacy scene runtime and enforces a non-decreasing boundary',()=>{
  assert.equal(files.length,31,'review newly added/deleted scene runtime files');
  assert(migrated.length>=31,'typed SCUI coverage must not fall below P13-14');
  assert(files.length-migrated.length<=0,'untyped scene debt must not increase');
 });
 it('retains canonical TypeScript sources for all generated scene runtimes',()=>{
  for(const [name,meta] of Object.entries(manifest)){
   const source=path.join(root,meta.source);
   const runtime=path.join(root,meta.runtime);
   assert(fs.existsSync(source),name+' missing canonical TypeScript source');
   assert(fs.existsSync(runtime),name+' missing emitted JS');
   assert(fs.readFileSync(runtime,'utf8').startsWith(
    '// GENERATED FROM '+meta.source+'\n'),name+' not generated by SCUI');
  }
  assert.equal(Object.keys(manifest).length,31);
 });
 it('binds the Bridge to typed controller, interaction, seek geometry and lifecycle ports',()=>{
  const text=fs.readFileSync(path.join(typed,'SceneSearchIntegrationBridge.ts'),'utf8');
  const remaining=(text.match(/\bBridgeLegacy\b/g)||[]).length;
  assert(remaining<=9,'P13 Bridge dynamic boundaries must not grow again');
  for(const contract of [
   'declare controller:BridgeControllerPort;',
   'declare interaction:BridgeInteractionPort;',
   'declare idleLimiter:BridgeIdlePort;',
   'declare commentSearch:BridgeCommentModelPort;',
   'declare router:BridgeRouterPort;',
   'declare _placementGeometry:BridgePlacementGeometry|null;',
   'declare _active:BridgeActiveCard|null;',
   '_startPointer(e:{pointerId?:number|string}|null):void',
   'const pointer=(e:PointerEvent)'
  ])assert(text.includes(contract),contract+' lost its typed owner');
 });
 it('keeps the native VideoControlBar source typed but acknowledges remaining loose typing',()=>{
  const text=fs.readFileSync(path.join(typed,'VideoControlBar.ts'),'utf8');
  assert(text.includes('class VideoControlBar extends Emitter'));
  const remaining=(text.match(/\bLoose\b/g)||[]).length;
  assert(remaining>0,'when all loose types are removed update the completion gate');
  assert(remaining<=234,'P13-17 seek/pin/resume native field typing must not regress');
  for(const field of [
   'declare _sceneSearchPinnedTime: NativeScenePinnedTime;',
   'declare _seekBar: HTMLElement;',
   'declare _seekRange: HTMLInputElement;',
   'declare _seekBarMouseX: number|null;',
   'declare _seekBarToolTip: NativeSceneSeekTooltip;',
   'declare $resumePointers: NativeResumePointerTargets;',
   'declare _duration: number;'
  ])assert(text.includes(field),field+' lost its explicit owner type');
  for(const handler of [
   '_onSeekRangeInput(e:Event&{target:HTMLInputElement})',
   '_onSeekBarMouseDown(e:MouseEvent)',
   '_onSeekBarMouseMove(e:MouseEvent)',
   '_onBodyMouseUp(e:MouseEvent)'
  ])assert(text.includes(handler),handler+' lost native event typing');
 });
});
