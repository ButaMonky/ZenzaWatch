// Fixed P12 manual-bookmark TypeScript -> runtime boundary, local only.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
const srcDir='tools/typescript-stage1/p12-src/';
const emitDir='tools/typescript-stage1/.generated/p12/';
const runtimeDir='packages/zenza/src/resume/';
const manifest='tools/typescript-stage1/p12-manual-manifest.json';
const specs=Object.freeze([
 {name:'ManualBookmarkPolicy',imports:[],tops:[
  'const MAX_PER_VIDEO','const validId','const validClock','const validTime',
  'const labelFor','};','const immutable','const forVideo','};',
  'export function normalizeManualBookmarks','}',
  'export function addManualBookmark','}',
  'export function renameManualBookmark','}',
  'export function removeManualBookmark','}']},
 {name:'ManualBookmarkStore',imports:[
  "import { normalizeManualBookmarks, addManualBookmark, renameManualBookmark, removeManualBookmark } from './ManualBookmarkPolicy.js';"
 ],tops:['const databaseName','const storeName','const validateVideoId',
  'export class IndexedDbManualBookmarkBackend','}',
  'export class ManualBookmarkRepository','}']},
 {name:'ManualBookmarkSession',imports:[],tops:[
  'const empty','const valid','const immutable','const makeState',
  'export class ManualBookmarkSession','}']},
 {name:'ManualBookmarkPanel',imports:[],tops:[
  'const displayTime','};','export class ManualBookmarkPanel','}']},
 {name:'ManualBookmarkDock',imports:[
  "import { ManualBookmarkPanel } from './ManualBookmarkPanel.js';"
 ],tops:['const contentSelector','export class ManualBookmarkDock','}']}
]);
const fail=code=>{throw Error('P12_MANUAL_'+code);};
const file=p=>path.join(root,p);
const read=p=>fs.existsSync(file(p))?
  fs.readFileSync(file(p),'utf8').replace(/\r\n/g,'\n'):null;
const sha=s=>createHash('sha256').update(s).digest('hex');
function emittedRuntime(spec,compiled){
 if(typeof compiled!=='string')fail('MISSING_EMITTED_'+spec.name);
 const imports=compiled.split('\n').filter(x=>/^import\s/.test(x));
 if(JSON.stringify(imports)!==JSON.stringify(spec.imports)){
  fail('UNEXPECTED_IMPORT_'+spec.name);
 }
 if(/\b(?:require|eval)\s*\(/.test(compiled)||
   /\bimport\s*\(/.test(compiled))fail('DYNAMIC_IMPORT_'+spec.name);
 const tops=compiled.split('\n').filter(x=>/^\S/.test(x)&&
  !/^(?:\/\/|\/\*|\*|\*\/|import\s)/.test(x));
 if(tops.length!==spec.tops.length||tops.some((line,i)=>
   !line.startsWith(spec.tops[i]))){
   fail('TOP_LEVEL_SHAPE_'+spec.name);
 }
 const expectedExports=spec.tops.filter(line=>line.startsWith('export '));
 const actualExports=tops.filter(line=>line.startsWith('export '));
 if(expectedExports.length!==actualExports.length||
   actualExports.some((value,i)=>!value.startsWith(expectedExports[i]))){
   fail('EXPORT_SHAPE_'+spec.name);
 }
 const names=actualExports.map(line=>{
  const match=/^export (?:class|function) ([A-Za-z_$][A-Za-z0-9_$]*)/.exec(line);
  if(!match)fail('EXPORT_NAME_'+spec.name);
  return match[1];
 });
 const body=compiled.split('\n').filter(line=>!spec.imports.includes(line))
  .join('\n').replace(/^export (class|function) /gm,'$1 ').trimEnd();
 if(/^\s*(?:import|export)\s/m.test(body)||
   body.includes('//===BEGIN===')||body.includes('//===END===')){
   fail('UNEXPECTED_MODULE_DIRECTIVE_'+spec.name);
 }
 const deps=spec.name==='ManualBookmarkStore'?['normalizeManualBookmarks']:
   spec.name==='ManualBookmarkDock'?['ManualBookmarkPanel']:[];
 return [...spec.imports,'// GENERATED FROM '+srcDir+spec.name+'.ts',
  '// Fixed P12 manual bookmark runtime. Do not edit this file.',
  '//===BEGIN===',...deps.map(dep=>'//@require '+dep),
  'const {'+names.join(', ')+'} = (() => {',
  body,'return {'+names.join(', ')+'};','})();',
  '//===END===','export {'+names.join(', ')+'};',''].join('\n');
}
export function sync(mode){
 if(mode!=='--write'&&mode!=='--check')fail('BAD_MODE');
 const generated=specs.map(spec=>{
  const source=srcDir+spec.name+'.ts';
  const emitted=emitDir+spec.name+'.js';
  const runtime=runtimeDir+spec.name+'.js';
  const src=read(source),compiled=read(emitted);
  if(src===null)fail('MISSING_SOURCE_'+spec.name);
  const output=emittedRuntime(spec,compiled);
  return {name:spec.name,source,emitted,runtime,src,compiled,output,
    current:read(runtime)};
 });
 const oldText=read(manifest);
 let old=null;
 if(oldText!==null){
  try{old=JSON.parse(oldText);}catch{fail('MANIFEST_INVALID');}
  if(old?.version!==1||!Array.isArray(old.modules)||
    old.modules.length!==generated.length||
    old.modules.some((x,i)=>x.name!==generated[i].name||
      x.source!==generated[i].source||
      x.runtime!==generated[i].runtime||
      !/^[a-f0-9]{64}$/.test(x.runtimeSha256||''))){
    fail('MANIFEST_DRIFT');
  }
 }
 const next=JSON.stringify({version:1,modules:generated.map(item=>({
  name:item.name,source:item.source,runtime:item.runtime,
  sourceSha256:sha(item.src),emittedSha256:sha(item.compiled),
  runtimeSha256:sha(item.output)
 }))},null,2)+'\n';
 if(mode==='--check'){
  if(oldText!==next||generated.some(item=>item.current!==item.output)){
    fail('STALE_RUNTIME_OR_MANIFEST');
  }
  return {modules:generated.length,status:'PASS'};
 }
 // New files require a new manifest. Existing files require their last
 // accepted hash: never silently claim a foreign implementation.
 for(const [i,item] of generated.entries()){
  if(item.current!==null&&(!old||
    sha(item.current)!==old.modules[i].runtimeSha256)){
    fail('FOREIGN_RUNTIME_EDIT_'+item.name);
  }
  if(item.current===null&&old)fail('MISSING_TRACKED_RUNTIME_'+item.name);
 }
 if(generated.some(item=>read(item.runtime)!==item.current)||
   read(manifest)!==oldText)fail('CONCURRENT_EDIT');
 const written=[];
 try{
  for(const item of generated){
   fs.mkdirSync(path.dirname(file(item.runtime)),{recursive:true});
   fs.writeFileSync(file(item.runtime),item.output,'utf8');
   written.push(item);
  }
  fs.writeFileSync(file(manifest),next,'utf8');
 }catch(error){
  // Revert only paths written by this generator. Do not discard other WIP.
  for(const item of written.reverse()){
   if(item.current===null)fs.unlinkSync(file(item.runtime));
   else fs.writeFileSync(file(item.runtime),item.current,'utf8');
  }
  if(oldText===null){if(fs.existsSync(file(manifest)))fs.unlinkSync(file(manifest));}
  else fs.writeFileSync(file(manifest),oldText,'utf8');
  throw error;
 }
 return {modules:generated.length,status:'PASS'};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{
  if(process.argv.length!==3)fail('BAD_ARGUMENTS');
  console.log('P12_MANUAL_SYNC '+JSON.stringify(sync(process.argv[2])));
 }catch(error){console.error(error.message);process.exitCode=1;}
}
